CREATE TABLE IF NOT EXISTS clientes (
 id INTEGER PRIMARY KEY AUTOINCREMENT, nome TEXT NOT NULL, telefone TEXT NOT NULL, email TEXT
);
CREATE TABLE IF NOT EXISTS veiculos (
 id INTEGER PRIMARY KEY AUTOINCREMENT, cliente_id INTEGER NOT NULL REFERENCES clientes(id), modelo TEXT NOT NULL,
 tipo TEXT NOT NULL, placa TEXT, marca TEXT, ano INTEGER CHECK (ano IS NULL OR typeof(ano) = 'integer')
);
CREATE TABLE IF NOT EXISTS tickets (
 id INTEGER PRIMARY KEY AUTOINCREMENT, cliente_id INTEGER NOT NULL REFERENCES clientes(id),
 veiculo_id INTEGER NOT NULL REFERENCES veiculos(id), defeito TEXT NOT NULL,
 status TEXT NOT NULL DEFAULT 'RECEBIDO' CHECK(status IN
 ('RECEBIDO','DIAGNOSTICO','AGUARDANDO_PECA','EM_MANUTENCAO','PRONTO','ENTREGUE','CANCELADO')),
 criado_em DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS atualizacoes (
 id INTEGER PRIMARY KEY AUTOINCREMENT, ticket_id INTEGER NOT NULL REFERENCES tickets(id) ON DELETE CASCADE,
 descricao TEXT NOT NULL, valor_servico NUMERIC(12,2) DEFAULT 0
);
CREATE TABLE IF NOT EXISTS orcamentos (
 id INTEGER PRIMARY KEY AUTOINCREMENT, ticket_id INTEGER NOT NULL UNIQUE REFERENCES tickets(id) ON DELETE CASCADE,
 valor_total NUMERIC(12,2) NOT NULL, status TEXT NOT NULL DEFAULT 'PENDENTE'
);
